import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import type { MigrationMeta } from "drizzle-orm/migrator";

const migrationsDirectory = new URL("../drizzle/", import.meta.url);
const outputUrl = new URL("../src/lib/server/db/migrations.generated.ts", import.meta.url);
const statementBreakpoint = "--> statement-breakpoint";

function folderMillis(name: string) {
  const date = name.slice(0, 14);
  if (!/^\d{14}$/.test(date)) {
    throw new Error(`Migration folder must start with a 14-digit timestamp: ${name}`);
  }
  return Date.UTC(
    Number(date.slice(0, 4)),
    Number(date.slice(4, 6)) - 1,
    Number(date.slice(6, 8)),
    Number(date.slice(8, 10)),
    Number(date.slice(10, 12)),
    Number(date.slice(12, 14)),
  );
}

function migrationManifest() {
  return readdirSync(migrationsDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map(({ name }) => name)
    .sort()
    .map((name) => {
      const sqlUrl = new URL(`${name}/migration.sql`, migrationsDirectory);
      const query = readFileSync(sqlUrl, "utf8");
      return {
        sql: query.split(statementBreakpoint),
        bps: true,
        folderMillis: folderMillis(name),
        hash: createHash("sha256").update(query).digest("hex"),
        name,
      } satisfies MigrationMeta;
    });
}

function generatedSource() {
  return `// Generated by scripts/embed-migrations.ts. Do not edit.\nimport type { MigrationMeta } from "drizzle-orm/migrator";\n\nexport const migrations = ${JSON.stringify(migrationManifest(), null, 2)} satisfies MigrationMeta[];\n`;
}

const expected = generatedSource();
const outputPath = fileURLToPath(outputUrl);
if (process.argv.includes("--check")) {
  let current: string | undefined;
  try {
    current = readFileSync(outputUrl, "utf8");
  } catch {
    // Report the same actionable stale-manifest error for a missing file.
  }
  if (current !== expected) {
    throw new Error("Embedded migrations are stale. Run `pnpm migrations:embed`.");
  }
} else {
  writeFileSync(outputPath, expected);
  console.log(`Embedded ${migrationManifest().length} migrations in ${outputPath}`);
}
